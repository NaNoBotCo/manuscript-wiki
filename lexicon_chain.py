def apply_chain(d, spec, conf="probable"):
    n = 0
    by = {s["n"]: s for s in d["senses"]}
    for sn, (parent, via, why) in spec.items():
        s = by.get(sn)
        if not s or parent not in by or parent == sn:
            continue
        s["extends"] = parent
        s["via"] = via
        s["via_note"] = why
        s["via_conf"] = conf
        n += 1
    return n


def core_sense(d):
    """The most concrete literal sense to hang a name-use on: the first sense that
    is not itself a naming, a classifier use, or a figurative reading."""
    for s in d["senses"]:
        g = (s["gloss"].get("th") or "").strip()
        if g.startswith("ชื่อ") or g == MARKER or "ปริยาย" in g:
            continue
        return s["n"]
    return d["senses"][0]["n"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nameuse", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()

    stats = {"nameuse": 0, "hand": 0, "entries": 0, "mapped": 0}
    for f in sorted((LEX / "entries").glob("*.json")):
        d = json.loads(f.read_text("utf-8"))
        before = sum(1 for s in d["senses"] if s.get("extends"))
        touched = 0

        if a.nameuse:
            for s in d["senses"]:
                if (s["gloss"].get("th") or "").strip() == MARKER and not s.get("extends"):
                    p = core_sense(d)
                    if p != s["n"]:
                        s["extends"] = p
                        s["via"] = "metonymy"
                        s["via_note"] = (
                            "A place is named for the feature it has — the feature "
                            "stands in for the location. That is metonymy rather than "
                            "metaphor: the marsh, the field, the creek is actually "
                            "there, and the name points at it.")
                        s["via_conf"] = "probable"
                        touched += 1
                        stats["nameuse"] += 1

        for sn, why in ROOTS.get(d["th"], {}).items():
            for s in d["senses"]:
                if s["n"] == sn and why not in (s.get("needs_check") or []):
                    s.setdefault("needs_check", []).append("Declared root: " + why)
                    touched += 1

        for (th, sn), why in SEPARATE.items():
            if d["th"] == th:
                for s in d["senses"]:
                    if s["n"] == sn and why not in (s.get("needs_check") or []):
                        s.setdefault("needs_check", []).append(why)
                        touched += 1

        if d["th"] in CHAINS:
            n = apply_chain(d, CHAINS[d["th"]])
            touched += n
            stats["hand"] += n

        if touched:
            stats["entries"] += 1
            # Mapped means every sense but ONE has a parent — and the parentless
            # one need not be sense 1. ใจ's core is its organ sense, which the RID
            # printed second; the chain says so and the numbering stays put.
            declared = set(ROOTS.get(d["th"], {}))
            loose = [s for s in d["senses"]
                     if not s.get("extends") and s["n"] not in declared]
            need = len(d["senses"]) - 1
            ok = (len(loose) == 1 and not declared) or (declared and not loose)
            if ok and need > 0:
                d["status"] = "mapped"
                stats["mapped"] += 1
            if a.write:
                f.write_text(json.dumps(d, ensure_ascii=False, indent=1) + "\n", "utf-8")

    print(f"EXTENDS written: {stats['nameuse']} name-use (uniform argument) + "
          f"{stats['hand']} hand-reasoned")
    print(f"entries touched: {stats['entries']} · reached status mapped: {stats['mapped']}")
    if not a.write:
        print("(dry run — pass --write)")


if __name__ == "__main__":
    main()
